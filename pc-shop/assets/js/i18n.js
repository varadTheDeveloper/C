(function () {
  var KEY = "cw-lang";
  var LANGS = ["mr", "hi", "en"];

  function saved() {
    try { return localStorage.getItem(KEY); } catch (e) { return null; }
  }

  var current = LANGS.indexOf(saved()) >= 0 ? saved() : "mr";

  function t(key, vars) {
    var s = (I18N[current] && I18N[current][key]) || I18N.en[key] || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) { s = s.replace("{" + k + "}", vars[k]); });
    }
    return s;
  }

  function apply(root) {
    (root || document).querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    (root || document).querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    (root || document).querySelectorAll("[data-i18n-label]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-label")));
    });
    document.documentElement.lang = current;
    document.querySelectorAll("[data-lang]").forEach(function (b) {
      b.setAttribute("aria-pressed", b.getAttribute("data-lang") === current ? "true" : "false");
    });
  }

  function set(lang) {
    if (LANGS.indexOf(lang) < 0) return;
    current = lang;
    try { localStorage.setItem(KEY, lang); } catch (e) {}
    apply();
    document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
  }

  window.i18n = { t: t, apply: apply, set: set, get lang() { return current; } };
})();
